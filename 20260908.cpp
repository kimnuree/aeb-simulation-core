
#include <iostream>


int main() {
	using namespace std;
	int a = 6;
	int* b = &a;// a의 주소 가 b Reference (&
	*b = *b + 1; // *b is 주소 b안에 있는 내용물 Dereference Operator (*




	//new 연산자: "이름 없는 무인 물품보관소 빌리기"
	// 4. 무인 보관소에 새 칸을 빌리고, 그 번호를 메모지에 적기 (new 연산자)
	int* storageKey = new int; //4바이트 × 1 = 4바이트

		// 5. 빌린 보관함 번호로 찾아가서 100을 넣어두기
	*storageKey = 100;

		// 6. 다 썼으니 보관함 반납하기 (delete)
	delete storageKey;

	double* p3 = new double[3]; //8바이트 × 3 = 24바이트

	p3[0] = 1.1; //C++ 문법에서 대괄호 [ ]는 내부적으로 포인터 연산자 *로 자동 변환됩니다.

	p3[1] = 2.2;
	p3[2] = 3.3;

	p3 = p3 + 1; // 포인터 연산자 +, -를 사용하면, 자료형의 크기만큼 이동합니다. (double은 8byte이므로, 8byte 이동)

	p3 = p3 - 1; 
	
	delete[] p3; // new로 할당받은 동적 메모리는 반드시 delete로 해제해야 합니다. (delete[]는 배열 해제용)
/* 

delete ptr; (단일 해제): 포인터가 가리키는 맨 첫 번째 원소 딱 1개만 해제하고 끝냅니다.

delete[] ptr; (배열 해제): 배열 안에 들어있는 모든 원소(개수만큼)를 
하나씩 찾아가 전부 안전하게 정리(소멸자 호출)한 뒤 반납합니다.

`p3 = p3 + 1;`은 **포인터가 가리키는 메모리 주소를 바로 옆(다음 칸) 위치로 1칸
 이동시키는 연산**입니다.

---

**1. 코드 실행 시 발생하는 일**

* **원래 상태 (`p3` 초기 위치):**
`p3`는 `new double[3]`으로 만들어진 연속된 3개 보관함 중 **첫 번째 
보관함(`p3[0]`, 값 `0.2`)의 주소**를 가리키고 있습니다.
* **`p3 = p3 + 1;` 실행 후:**
주소 자체가 `double` 타입 크기(8바이트)만큼 증가하면서, `p3`가 **두 번째 
보관함(`0.5`가 들어있는 위치)을 새로운 기준점**으로 바라보게 됩니다.

---

**2. 이동 후 `p3[0]`의 값이 바뀌는 이유**

주소 기준점이 다음 칸으로 이동했기 때문에 대괄호 `[ ]`로 접근할 때 가져오는 값이 달라집니다.

* **이동 전:** `p3[0]` $\rightarrow$ `0.2` (첫 번째 칸)
* **`p3 = p3 + 1;` 이동 후:**
* **`p3[0]`**: 이동한 위치가 새로운 0번이 되므로 원래 두 번째 값인 `0.5`가 출력됩니다.
* **`p3[1]`**: 이동한 위치의 다음 칸이 되므로 원래 세 번째 값인 `0.8`이 출력됩니다.



---

**3. 코드 아래쪽에 `p3 = p3 - 1;`을 다시 해주는 이유**

`new` 연산자로 할당받은 동적 메모리를 반납(`delete[] p3;`)할 때는 반드시 컴퓨터가 
메모리를 처음 빌려주었던 '원래 시작 주소'를 전달해야 합니다.

주소가 1칸 앞으로 밀려난 상태에서 `delete[] p3;`를 하면 에러(프로그램 다운)가 발생하므로,
 메모리를 해제하기 직전에 `p3 = p3 - 1;`로 주소를 다시 제자리로 되돌려놓는 것입니다.


*/












	return 0;





}


